"""Build an offline HTML gallery and portable ZIP from figures and TOML legends.

Images and PDFs stay in place and are linked using relative URLs, so the gallery
can be opened directly without a web server. A ZIP includes the gallery and its
linked files with their project-relative paths preserved.
"""

import argparse
from collections import defaultdict
import html
import json
import os
from pathlib import Path
import re
import tempfile
import tomllib
from urllib.parse import quote, unquote
import zipfile


IMAGE_TYPES = (".png", ".svg", ".webp", ".jpg", ".jpeg", ".gif")
FILE_TYPES = (*IMAGE_TYPES, ".pdf")
GENERATED_MARKER = "<!-- Generated by figure-gallery; edit figures.legends.toml and rebuild. -->"


def validate_key(key: str, group: str) -> None:
    if group == "sections" and key == ".":
        return
    if not key or "\\" in key or any(part in {"", ".", ".."} for part in key.split("/")):
        raise ValueError(f"Invalid {group} key: {key!r}; use figure-relative POSIX paths")
    if group == "sections" and "/" in key:
        raise ValueError(f"Section key must name a top-level figure folder: {key!r}")


def inside_root(path: Path, root: Path) -> Path:
    """Check resolved containment, but retain the linked spelling for ZIP names."""
    path = Path(os.path.abspath(path))
    if not path.is_relative_to(root) or not path.resolve().is_relative_to(root):
        raise ValueError(f"Gallery files must be inside the atomic folder ({root}): {path}")
    return path


def read_legends(path: Path) -> dict:
    with path.open("rb") as handle:
        legends = tomllib.load(handle)
    unknown = legends.keys() - {"title", "description", "sections", "plots"}
    if unknown:
        raise ValueError(f"Unknown legend settings: {', '.join(sorted(unknown))}")
    for key in ("title", "description"):
        if key in legends and not isinstance(legends[key], str):
            raise ValueError(f"Legend {key} must be text")
    for group in ("sections", "plots"):
        entries = legends.get(group, {})
        if not isinstance(entries, dict):
            raise ValueError(f"Legend {group} must be a TOML table")
        allowed = {"title", "description"}
        if group == "plots":
            allowed.add("download_only")
        else:
            allowed.update({"text", "source", "link_label", "download"})
        for name, entry in entries.items():
            validate_key(name, group)
            if not isinstance(entry, dict) or entry.keys() - allowed:
                raise ValueError(f"Invalid settings for {group}.{name}")
            for key in ("title", "description", "text", "source", "link_label"):
                if key in entry and not isinstance(entry[key], str):
                    raise ValueError(f"{group}.{name}.{key} must be text")
            if "download_only" in entry and not isinstance(entry["download_only"], bool):
                raise ValueError(f"{group}.{name}.download_only must be true or false")
            if "download" in entry and not isinstance(entry["download"], bool):
                raise ValueError(f"{group}.{name}.download must be true or false")
            if group == "sections" and entry.get("download") and not entry.get("source"):
                raise ValueError(f"sections.{name}.download requires a source")
            if group == "sections" and entry.get("link_label") and not entry.get("source"):
                raise ValueError(f"sections.{name}.link_label requires a source")
            if group == "sections" and entry.get("source") and not entry.get("text", "").strip():
                raise ValueError(f"sections.{name}.source requires a text section")
    return legends


def readable_name(name: str) -> str:
    return name.replace("_", " ").replace("-", " ").capitalize()


def relative_url(path: Path, output: Path) -> str:
    return quote(Path(os.path.relpath(path, output.parent)).as_posix(), safe="/")


def discover_figures(figure_dir: Path, output: Path, legends: dict) -> list[dict]:
    section_legends = legends.get("sections", {})
    plot_legends = legends.get("plots", {})
    download_only = [key for key, entry in plot_legends.items() if entry.get("download_only")]
    files = defaultdict(dict)
    for path in sorted(figure_dir.rglob("*")):
        relative = path.relative_to(figure_dir)
        suffix = path.suffix.lower()
        if (not path.is_file() or suffix not in FILE_TYPES
                or any(part.startswith(".") for part in relative.parts)):
            continue
        key = relative.with_suffix("").as_posix()
        if suffix in files[key]:
            raise ValueError(f"Multiple {suffix} files for plot {key}")
        files[key][suffix] = path

    # A multipage report is one PDF entry, rather than dozens of PNG pages.
    for report in download_only:
        companions = [key for key in files
                      if key == report or re.fullmatch(re.escape(report) + r"_\d+", key)]
        if not companions:
            continue
        if ".pdf" not in files.get(report, {}):
            raise ValueError(f"Download-only plot {report} requires a PDF")
        for key in companions:
            files[key] = {ext: path for ext, path in files[key].items() if ext == ".pdf"}
            if not files[key]:
                del files[key]

    missing_plots = plot_legends.keys() - files.keys()
    if missing_plots:
        raise ValueError(f"Configured plots not found: {', '.join(sorted(missing_plots))}")

    if not files and not any(legend.get("text", "").strip() for legend in section_legends.values()):
        raise ValueError(f"No supported figures or text sections found in {figure_dir}")
    section_order = {key: position for position, key in enumerate(section_legends)}
    plot_order = {key: position for position, key in enumerate(plot_legends)}
    grouped = defaultdict(list)
    for key in sorted(files, key=lambda key: (plot_order.get(key, len(plot_order)), key)):
        formats = files[key]
        legend = plot_legends.get(key, {})
        image = next((formats[ext] for ext in IMAGE_TYPES if ext in formats), None)
        section = key.split("/", 1)[0] if "/" in key else "."
        grouped[section].append({
            "id": key,
            "title": legend.get("title", readable_name(Path(key).name)),
            "description": legend.get("description", "").strip(),
            "preview": relative_url(image, output) if image else None,
            "files": [
                {"format": ext[1:].upper(), "url": relative_url(formats[ext], output)}
                for ext in (".pdf", *IMAGE_TYPES) if ext in formats
            ],
        })

    section_keys = set(grouped) | {
        key for key, legend in section_legends.items() if legend.get("text", "").strip()
    }
    sections = []
    for key in sorted(section_keys, key=lambda key: (section_order.get(key, len(section_order)), key)):
        legend = section_legends.get(key, {})
        text = legend.get("text", "").strip()
        if text and grouped.get(key):
            raise ValueError(f"Text-only section {key} cannot also contain figures")
        sections.append({
            "id": key,
            "title": legend.get("title", "Other figures" if key == "." else readable_name(key)),
            "description": legend.get("description", "").strip(),
            "plots": grouped.get(key, []),
            "text": text,
            "link_label": legend.get("link_label", "Read the full source note"),
            "download": legend.get("download", False),
        })
    return sections


def build_gallery(
    figure_dir: Path, legends_path: Path, output: Path, template: Path | None = None,
) -> tuple[str, list[dict]]:
    if not figure_dir.is_dir():
        raise ValueError(f"Figure directory does not exist: {figure_dir}")
    if output.suffix.lower() != ".html":
        raise ValueError("Gallery output must have an .html extension")
    legends = read_legends(legends_path)
    sections = discover_figures(figure_dir, output, legends)
    entry_ids = []
    for section in sections:
        entry_ids.extend([section["id"]] if section["text"] else
                         [plot["id"] for plot in section["plots"]])
        source = legends.get("sections", {}).get(section["id"], {}).get("source")
        if source:
            source_path = (legends_path.parent / source).resolve()
            if not source_path.is_file():
                raise ValueError(f"Section source does not exist: {source_path}")
            section["source"] = relative_url(source_path, output)
    if len(entry_ids) != len(set(entry_ids)):
        raise ValueError("Text sections and plots must have distinct navigation IDs")
    title = legends.get("title", "Figure library")
    data = {"sections": sections}
    # Escape HTML delimiters in JSON, including literal closing script tags in
    # user-authored legends. All legend text is rendered with textContent.
    payload = json.dumps(data, ensure_ascii=False).replace("&", "\\u0026")
    payload = payload.replace("<", "\\u003c").replace(">", "\\u003e")
    if template is None:
        template = Path(__file__).with_name("figure_gallery.html")
        if not template.is_file():
            template = Path(__file__).resolve().parents[1] / "assets" / "figure_gallery.html"
    template_text = template.read_text(encoding="utf-8")
    replacements = {
        "GALLERY_TITLE": html.escape(title),
        "GALLERY_DESCRIPTION": html.escape(legends.get("description", "").strip()),
        "GALLERY_DATA": payload,
    }
    for name in replacements:
        if f"@@{name}@@" not in template_text:
            raise ValueError(f"Template is missing @@{name}@@")
    unknown = set(re.findall(r"@@(GALLERY_[A-Z_]+)@@", template_text)) - replacements.keys()
    if unknown:
        raise ValueError(f"Unknown template slots: {', '.join(sorted(unknown))}")
    document = re.sub(r"@@(GALLERY_[A-Z_]+)@@", lambda match: replacements[match[1]], template_text)
    if GENERATED_MARKER not in document:
        document = GENERATED_MARKER + "\n" + document
    return document, sections


def bundle_files(output: Path, sections: list[dict], root: Path) -> dict[str, Path]:
    """Validate all linked files before publishing either generated artifact."""
    files = set()
    for section in sections:
        files.update(
            output.parent / unquote(entry["url"])
            for plot in section["plots"]
            for entry in plot["files"]
        )
        if section.get("source"):
            files.add(output.parent / unquote(section["source"]))

    archive_files = {}
    for path in sorted(files):
        path = inside_root(path, root)
        if not path.is_file():
            raise ValueError(f"Gallery bundle file does not exist: {path}")
        if path == output:
            raise ValueError("The gallery output cannot also be a linked source file")
        archive_path = path.relative_to(root)
        archive_files[archive_path.as_posix()] = path
    return archive_files


def write_outputs(document: str, output: Path, sections: list[dict], root: Path) -> Path:
    archive_files = bundle_files(output, sections, root)
    zip_path = output.with_name("figure_gallery.zip")
    if zip_path in archive_files.values():
        raise ValueError("The gallery archive cannot also be a linked source file")
    output.parent.mkdir(parents=True, exist_ok=True)
    # Stage both artifacts first; validation errors leave previous builds intact.
    with tempfile.TemporaryDirectory(dir=output.parent, prefix=".figure-gallery-") as staging:
        html_temp = Path(staging) / "index.html"
        html_temp.write_text(document, encoding="utf-8")
        zip_temp = Path(staging) / "gallery.zip"
        with zipfile.ZipFile(zip_temp, "w", compression=zipfile.ZIP_DEFLATED) as archive:
            archive.writestr(output.relative_to(root).as_posix(), document.encode("utf-8"))
            for archive_name, path in archive_files.items():
                archive.write(path, archive_name)
        zip_temp.replace(zip_path)
        html_temp.replace(output)
    return zip_path


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--root", type=Path, default=Path.cwd(), help="Atomic folder (default: cwd)")
    parser.add_argument("--figure-dir", type=Path, default=Path("figures"))
    parser.add_argument("--legends", type=Path, default=Path("figures.legends.toml"))
    parser.add_argument("--output", type=Path, help="Default: <figure-dir>/index.html")
    parser.add_argument("--template", type=Path, help="Override the bundled HTML template")
    parser.add_argument(
        "--replace-existing-gallery", action="store_true",
        help="Replace a previously inspected HTML output made by another builder",
    )
    args = parser.parse_args()
    root = args.root.resolve()
    try:
        if not root.is_dir():
            raise ValueError(f"Atomic folder does not exist: {root}")
        figure_dir = inside_root(root / args.figure_dir, root)
        legends_path = inside_root(root / args.legends, root)
        output = inside_root(root / (args.output or figure_dir / "index.html"), root)
        inside_root(output.with_name("figure_gallery.zip"), root)
        if output.is_symlink():
            raise ValueError("Gallery output must not be a symlink")
        if output.exists() and GENERATED_MARKER not in output.read_text(encoding="utf-8"):
            if not args.replace_existing_gallery:
                raise ValueError(
                    f"Refusing to replace an unrecognized HTML report: {output}. "
                    "Inspect its consumers before using --replace-existing-gallery."
                )
        template = (root / args.template).resolve() if args.template else None
        document, sections = build_gallery(figure_dir, legends_path, output, template)
        zip_path = write_outputs(document, output, sections, root)
    except (OSError, ValueError) as error:
        parser.exit(1, f"Figure gallery failed: {error}\n")
    plots = [plot for section in sections for plot in section["plots"]]
    downloads = sum(plot["preview"] is None for plot in plots)
    print(f"Built {len(sections)} sections, {len(plots)} plots ({downloads} PDF-only): {output}")
    print(f"Bundled gallery and linked files: {zip_path}")


if __name__ == "__main__":
    main()
